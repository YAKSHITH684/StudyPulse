// Fallback proxy that provides graceful fallback for all 29+ languages
export const translations = new Proxy(baseTranslations, {
  get: (target, langCode) => {
    if (target[langCode]) {
      return new Proxy(target[langCode], {
        get: (langTarget, prop) => {
          if (prop in langTarget) return langTarget[prop];
          if (target.en && prop in target.en) return target.en[prop];
          return prop;
        }
      });
    }
    // Return localized English/Hindi fallback with language native name
    const langMeta = INDIC_LANGUAGES.find(l => l.code === langCode);
    const fallback = { ...target.en };
    if (langMeta) {
      fallback.appName = `StudyPulse (${langMeta.nativeName})`;
    }
    return fallback;
  }
});
